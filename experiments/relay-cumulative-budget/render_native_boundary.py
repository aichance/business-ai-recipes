#!/usr/bin/env python3
"""Render the recorded native startup comparison; makes no Codex/model calls.

From the repository root:
    python3 -B experiments/relay-cumulative-budget/render_native_boundary.py
    python3 -B experiments/relay-cumulative-budget/render_native_boundary.py --check
"""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).with_name("native-results-2026-10-27.json")
OUTPUT = ROOT / "docs/agent-relay-native-boundary.svg"


def render() -> str:
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    if (data["schema_version"], data["mode"], data["tool_version"],
            data["codex_version"], data["project_doc_max_bytes"]) != (
            1, "native-only", "0.1.4", "0.164.0", 32768):
        raise ValueError("Unexpected measurement schema/version/budget")
    cases = {case["case"]: case for case in data["cases"]}
    if len(cases) != len(data["cases"]):
        raise ValueError("Duplicate measured case")
    names = ["parent_one_byte_left", "parent_budget_exhausted"]
    expected_paths = [["AGENTS.md", "child/AGENTS.md"], ["AGENTS.md"]]
    parents = []
    children = []
    for name, paths in zip(names, expected_paths):
        case = cases[name]
        relay = case["relay"]
        if (relay["status"] != "INSPECTED"
                or relay["native_project_sources"] != paths
                or relay["model_turn_requests"] != 0
                or relay["receipt"] != "NOT_TESTED"
                or relay["compliance"] != "NOT_TESTED"
                or relay["servers_started"] != relay["servers_closed"]
                or not relay["cleanup_confirmed"]
                or not case["fixture_and_config_unchanged"]):
            raise ValueError(f"Unexpected recorded scope/result: {name}")
        files = {item["path"]: item for item in relay["separate_local_estimate"]}
        parents.append(files["AGENTS.md"]["file_bytes"])
        children.append(files["child/AGENTS.md"]["file_bytes"])
    if parents != [32767, 32768] or children != [60, 60]:
        raise ValueError("Unexpected fixture byte sizes")
    if (cases[names[0]]["fixture_sha256"]["child/AGENTS.md"]
            != cases[names[1]]["fixture_sha256"]["child/AGENTS.md"]):
        raise ValueError("Child fixture bytes must be identical across conditions")

    # Only native path membership is depicted. Local examined-byte estimates
    # are deliberately omitted: they are not native delivery telemetry.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="700" viewBox="0 0 1200 700" role="img" aria-labelledby="title desc">
  <title id="title">One extra byte changes the native startup file list</title>
  <desc id="desc">Recorded operator fixtures with Codex 0.164.0 and Agent Relay Check 0.1.4. With a 32767-byte parent AGENTS.md, the native project file list includes child/AGENTS.md. With a 32768-byte parent, the same 60-byte child is absent. Zero model turns were requested. Listing does not prove full content receipt or compliance.</desc>
  <metadata>Source: experiments/relay-cumulative-budget/native-results-2026-10-27.json; SHA-256: {hashlib.sha256(raw).hexdigest()}; generated by render_native_boundary.py</metadata>
  <rect width="1200" height="700" rx="20" fill="#101a2c"/>
  <g font-family="Arial, Helvetica, sans-serif">
    <text x="48" y="58" font-size="20" fill="#a9bad4">AGENT RELAY CHECK · RECORDED OPERATOR FIXTURES</text>
    <text x="48" y="117" font-size="43" font-weight="700" fill="#ffffff">One extra byte changes the startup file list</text>
    <text x="48" y="156" font-size="22" fill="#bdcbe0">Codex 0.164.0 · Relay 0.1.4 · 2026-10-27 · budget: 32,768 bytes</text>
    <rect x="48" y="196" width="532" height="358" rx="16" fill="#1b2941" stroke="#3c5575"/>
    <rect x="620" y="196" width="532" height="358" rx="16" fill="#1b2941" stroke="#3c5575"/>
    <text x="76" y="236" font-size="21" fill="#bdcbe0">PARENT FIXTURE SIZE</text>
    <text x="648" y="236" font-size="21" fill="#bdcbe0">PARENT FIXTURE SIZE</text>
    <text x="76" y="292" font-size="46" font-weight="700" fill="#ffffff">{parents[0]:,} bytes</text>
    <text x="648" y="292" font-size="46" font-weight="700" fill="#ffffff">{parents[1]:,} bytes</text>
    <text x="562" y="324" font-size="22" font-weight="700" fill="#f9d289">+1 B</text>
    <text x="76" y="342" font-size="20" fill="#bdcbe0">NATIVE PROJECT PATHS</text>
    <text x="648" y="342" font-size="20" fill="#bdcbe0">NATIVE PROJECT PATHS</text>
    <text x="76" y="388" font-size="28" font-family="monospace" fill="#ffffff">AGENTS.md</text>
    <text x="648" y="388" font-size="28" font-family="monospace" fill="#ffffff">AGENTS.md</text>
    <rect x="68" y="407" width="492" height="54" rx="8" fill="#163e53"/>
    <text x="80" y="443" font-size="28" font-family="monospace" fill="#a6ebff">child/AGENTS.md</text>
    <rect x="640" y="407" width="492" height="54" rx="8" fill="#42362c"/>
    <text x="652" y="443" font-size="28" fill="#f9d289">Child is absent from this list</text>
    <text x="76" y="509" font-size="22" fill="#bdcbe0">Child fixture: {children[0]} bytes</text>
    <text x="648" y="509" font-size="22" fill="#bdcbe0">Same child bytes and hash</text>
    <text x="48" y="599" font-size="25" font-weight="700" fill="#ffffff">Listed does not mean fully received.</text>
    <text x="48" y="638" font-size="22" fill="#bdcbe0">0 requested model turns · Model receipt and compliance: NOT_TESTED</text>
    <text x="48" y="674" font-size="19" fill="#a9bad4">Native paths observed; byte sizes describe fixtures. This is a figure from saved results, not a screen recording.</text>
  </g>
</svg>
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the tracked SVG differs")
    args = parser.parse_args()
    result = render().encode("utf-8")
    if args.check:
        if OUTPUT.read_bytes() != result:
            raise SystemExit("Native comparison SVG differs; rerun this renderer")
        print("Native comparison SVG matches recorded source")
    else:
        OUTPUT.write_bytes(result)
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
