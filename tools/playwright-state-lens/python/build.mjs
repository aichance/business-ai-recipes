import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createStateLens, renderTimeline } from '../lens.mjs';

// Extract the actual browser callback at the public Page boundary. No app is run.
let observer, calls = 0;
const page = { url: () => 'http://state-lens-build.invalid', evaluate: async (fn) => {
  observer = fn.toString(); calls += 1;
  return '{"status":"OBSERVED","exists":false,"value":null}';
} };
const lens = createStateLens(page, { probes: [{ name: 'build', source: 'localStorage', key: 'build' }], screenshots: false });
await lens.checkpoint('extract');
assert.equal(calls, 1);
assert.ok(observer.startsWith('async '));
const version = lens.report().libraryVersion;
const title = 'STATE_LENS_TITLE_6b138ce9';
const templateReport = { schema: 4, libraryVersion: version, title, probes: [], checkpoints: [] };
const rendered = renderTimeline(templateReport);
const data = JSON.stringify(templateReport);
const boundary = '<script type="application/json" id="data">';
const start = rendered.indexOf(boundary) + boundary.length;
assert.ok(start > boundary.length);
assert.equal(rendered.slice(start, start + data.length), data);
const head = rendered.slice(0, start), tail = rendered.slice(start + data.length);
assert.equal(head.split(title).length - 1, 2);
const source = await readFile(new URL('../lens.mjs', import.meta.url));
let output = await readFile(new URL('./runtime.py', import.meta.url), 'utf8');
const fields = { VERSION: version, SOURCE_SHA256: createHash('sha256').update(source).digest('hex'), OBSERVER: observer, HTML_HEAD: head, HTML_TAIL: tail };
for (const [key, value] of Object.entries(fields)) {
  const marker = JSON.stringify(`@GENERATED_${key}@`);
  assert.equal(output.split(marker).length - 1, 1);
  output = output.replace(marker, () => JSON.stringify(value));
}
const license = await readFile(new URL('../LICENSE', import.meta.url), 'utf8');
output = '# Generated by python/build.mjs; do not hand-edit.\n# ruff: noqa: E501\n' + license.split('\n').map(line => line ? '# ' + line : '#').join('\n') + '\n' + output;
const destination = new URL('./state_lens.py', import.meta.url);
if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), output, 'Regenerate python/state_lens.py');
  console.log('Python generated collector/renderer: EXACT');
} else {
  await writeFile(destination, output);
  console.log(fileURLToPath(destination));
}
